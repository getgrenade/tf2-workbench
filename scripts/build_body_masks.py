"""Compile the user-supplied black-hide masks into one lossless bit atlas per class.
Run with Python + Pillow + numpy. Originals live in assets/bodygroup_masks.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/bodygroup_masks'
OUT=ROOT/'src/assets/bodyMasks'
OUT.mkdir(parents=True,exist_ok=True)
config={};cls=None
for raw in (SOURCE/'bodygroups.txt').read_text().splitlines():
    line=raw.split('#')[0].strip()
    if not line or line=='---':continue
    if line.startswith('['):cls=line[1:-1];config[cls]=[];continue
    fields=[f.strip() for f in line.split(',')];options=dict(f.split('=',1) for f in fields[1:] if '=' in f)
    config[cls].append((fields[0],options))
manifest={}
labels={'pouch_L':'Left pouch','pouch_R':'Right pouch','rightarm':'Right arm','leftarm':'Left arm','shoes_socks':'Shoes and socks','body_lower':'Lower body','coat_lower':'Lower coat','pouch_front':'Front pouch','pouch_rear':'Rear pouch','backpack_connector':'Backpack connector','upper_arms':'Upper arms','lower_arms':'Lower arms'}
def category(name):
    if name in ['head','eyes','hat','headphones','glasses','cigarette']:return 'head'
    if name in ['hands','gloves']:return 'hands'
    if 'arm' in name:return 'arms'
    if name=='legs':return 'legs'
    if 'shoes' in name:return 'feet'
    return 'torso'
for cls,entries in config.items():
    # Include authored masks omitted/commented out by the source UI, such as Sniper's darts.
    names={name for name,_ in entries}
    for file in sorted(SOURCE.glob(f'{cls}_*.png')):
        name=file.stem[len(cls)+1:]
        if name not in names:entries.append((name,{}))
    groups=[];bit=0;atlas=None
    for name,opt in entries:
        group={'id':name,'label':labels.get(name,name.replace('_',' ').capitalize()),'category':category(name)}
        if opt.get('nomask')!='true':
            image=np.asarray(Image.open(SOURCE/f'{cls}_{name}.png').convert('L'))
            if atlas is None:atlas=np.zeros(image.shape,dtype=np.uint16)
            assert image.shape==atlas.shape and bit<16
            atlas[image<128]|=1<<bit;group['bit']=bit;bit+=1
        if opt.get('nodraw'):group['material']=opt['nodraw']
        if cls=='engineer' and name=='rightarm':group['material']='mech_hand'
        groups.append(group)
    fallback=next(g for g in groups if g['id']==('shirt' if cls=='heavy' else 'vest' if cls=='demo' else 'body'))
    # Unpainted UV texels belong to the core body; isolation should not leave stray geometry visible.
    atlas[atlas==0]=1<<fallback['bit']
    rgb=np.zeros((*atlas.shape,3),dtype=np.uint8);rgb[:,:,0]=atlas&255;rgb[:,:,1]=atlas>>8
    Image.fromarray(rgb).save(OUT/f'{cls}.png',optimize=True)
    manifest[cls]=groups
(ROOT/'src/viewer/bodyGroupData.ts').write_text('// Generated by scripts/build_body_masks.py from supplied authored masks.\nexport const BODY_GROUP_DATA = '+json.dumps(manifest,indent=2)+' as const;\n',encoding='utf-8')
print('Compiled',sum('bit' in g for groups in manifest.values() for g in groups),'masks into',len(manifest),'atlases')
